function applyLanguage(lang) {
  const dict = translations[lang] || translations.fr;
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] !== undefined) el.textContent = dict[key];
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (dict[key] !== undefined) el.setAttribute("placeholder", dict[key]);
  });

  const whatsappFloat = document.getElementById("whatsappFloat");
  if (whatsappFloat) whatsappFloat.setAttribute("aria-label", dict.whatsapp_aria);

  document.getElementById("langFr").classList.toggle("active", lang === "fr");
  document.getElementById("langEn").classList.toggle("active", lang === "en");

  localStorage.setItem("ansic_lang", lang);
}

document.getElementById("langFr").addEventListener("click", () => applyLanguage("fr"));
document.getElementById("langEn").addEventListener("click", () => applyLanguage("en"));

const savedLang = localStorage.getItem("ansic_lang") || "fr";
applyLanguage(savedLang);

// ===== Menu mobile =====
const navToggle = document.getElementById("navToggle");
const siteNav = document.getElementById("siteNav");

navToggle.addEventListener("click", () => {
  const isOpen = siteNav.classList.toggle("open");
  navToggle.setAttribute("aria-expanded", isOpen ? "true" : "false");
});

siteNav.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", () => {
    siteNav.classList.remove("open");
    navToggle.setAttribute("aria-expanded", "false");
  });
});

// ===== Formulaire de signalement d'urgence =====
const alertForm = document.getElementById("alertForm");
const alertConfirm = document.getElementById("alertConfirm");

alertForm.addEventListener("submit", (e) => {
  e.preventDefault();
  const nom = document.getElementById("nomAlerte").value.trim();
  const tel = document.getElementById("telAlerte").value.trim();
  const gravite = document.getElementById("gravite").value;

  if (!nom || !tel || !gravite) {
    alertConfirm.style.color = "#C81E2C";
    alertConfirm.textContent = "Merci de compléter les champs obligatoires avant l'envoi.";
    return;
  }

  alertConfirm.style.color = "#14532D";
  alertConfirm.textContent = `Alerte enregistrée, ${nom}. Notre cellule opérationnelle vous rappelle au ${tel} dans les meilleurs délais.`;
  alertForm.reset();
});

// ===== Formulaire d'adhésion volontaire =====
const joinForm = document.getElementById("joinForm");
const formConfirm = document.getElementById("formConfirm");

joinForm.addEventListener("submit", (e) => {
  e.preventDefault();
  const fullname = document.getElementById("fullname").value.trim();
  const phone = document.getElementById("phone").value.trim();
  const profil = document.getElementById("profil").value;

  if (!fullname || !phone || !profil) {
    formConfirm.style.color = "#C81E2C";
    formConfirm.textContent = "Merci de renseigner votre nom, profil et téléphone.";
    return;
  }

  formConfirm.style.color = "#14532D";
  formConfirm.textContent = `Merci ${fullname}, votre candidature a été enregistrée. Notre équipe vous contactera au ${phone}.`;
  joinForm.reset();
});

